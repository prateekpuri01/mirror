async def ingest_one(session, *, docx_path: Path, profile_data: dict) -> dict | None:
    """Parse one .docx and write the corresponding rows. Returns a stats dict.

    Returns None if the document doesn't follow the app's layout (no
    structured research or experience found).
    """
    parsed = parse_docx(docx_path)

    owner_name = (profile_data.get("personal") or {}).get("name") or ""
    # Multi-word companies that would otherwise be truncated by the regex.
    # Auto-derive from the user's work_history so this works for any user;
    # callers can also extend via the env var INGEST_MULTIWORD_COMPANIES
    # (comma-separated) for companies referenced by past resumes that aren't
    # in the current work_history.
    work_companies = tuple(
        wh.get("employer", "")
        for wh in (profile_data.get("work_history") or [])
        if wh.get("employer") and " " in wh.get("employer", "")
    )
    env_extras = tuple(
        c.strip() for c in os.environ.get("INGEST_MULTIWORD_COMPANIES", "").split(",") if c.strip()
    )
    multiword = work_companies + env_extras

    company, title = parse_filename(
        docx_path.name,
        owner_name=owner_name,
        multiword_companies=multiword,
    )

    # Sanity check: if we couldn't extract any research entries AND no
    # employer headers, the document isn't using docx_builder's layout —
    # skip rather than write a malformed Document.
    if not parsed["selected_research"] and not parsed["experience"]:
        logger.warning(
            "SKIP %s — couldn't parse structured sections (likely older layout)",
            docx_path.name,
        )
        return None

    catalog = (profile_data.get("complete_profile") or {}).get("accomplishments") or []

    # Match research entries → accomplishment_ids; drop unmatched
    research_with_ids: list[dict] = []
    unmatched: list[str] = []
    for entry in parsed["selected_research"]:
        aid = match_accomplishment_id(entry.get("title", ""), catalog)
        if not aid:
            unmatched.append(entry.get("title", ""))
            continue
        research_with_ids.append(
            {
                "category_label": entry.get("category_label", ""),
                "title": entry.get("title", ""),
                "description": entry.get("description", ""),
                "accomplishment_id": aid,
            }
        )

    # Map experience employer display names → employer_keys
    experience: dict[str, dict] = {}
    for emp_display, bullets in parsed["experience"].items():
        if not bullets:
            continue
        emp_key = employer_key_fn(emp_display)
        experience[emp_key] = {
            "bullets": [{"text": b, "accomplishment_ids": []} for b in bullets],
        }

    # Build the synthetic Document (no FK to a Job — these resumes weren't
    # tied to job postings tracked in this app).
    content_json = {
        "tagline": parsed["tagline"],
        "summary": parsed["summary"],
        "selected_research": research_with_ids,
        "experience": experience,
        "publications": [],
        "technical_skills": parsed["technical_skills"],
        "awards": parsed["awards"],
        "_ingested_from": str(docx_path),
    }

    doc = Document(
        job_id=None,
        doc_type=DocType.resume,
        name=f"Past resume — {company} — {title}".strip(" —"),
        content_markdown=None,
        content_docx_path=str(docx_path),
        content_json=content_json,
        version=1,
    )
    session.add(doc)
    await session.flush()

    job_context = {
        "job_id": None,
        "job_title": title,
        "company_name": company,
        "score_excerpt": None,
    }

    stats = {
        "doc_id": str(doc.id),
        "filename": docx_path.name,
        "company": company,
        "title": title,
        "research_inserted": 0,
        "research_unmatched": unmatched,
        "bullet_sets_inserted": 0,
        "skills_inserted": 0,
        "summary_inserted": False,
        "tagline_inserted": False,
    }

    # research_description rows
    for entry in research_with_ids:
        desc = (entry.get("description") or "").strip()
        if not desc:
            continue
        await _add_memory_row(
            session,
            entity_type="research_description",
            entity_key=entry["accomplishment_id"],
            doc_id=doc.id,
            user_text=desc,
            user_payload_json=None,
            job_context=job_context,
            source_text_hash=content_memory_service.compute_source_hash(
                "research_description",
                [entry["accomplishment_id"]],
                profile_data,
            ),
        )
        stats["research_inserted"] += 1

    # experience_bullets_set rows
    for emp_key, block in experience.items():
        bullets_payload = block["bullets"]
        if not bullets_payload:
            continue
        accomp_ids = [aid for b in bullets_payload for aid in (b.get("accomplishment_ids") or [])]
        await _add_memory_row(
            session,
            entity_type="experience_bullets_set",
            entity_key=emp_key,
            doc_id=doc.id,
            user_text=None,
            user_payload_json=bullets_payload,
            job_context=job_context,
            source_text_hash=content_memory_service.compute_source_hash(
                "experience_bullets_set",
                accomp_ids,
                profile_data,
            ),
        )
        stats["bullet_sets_inserted"] += 1

    # skill_bucket rows
    for bucket, value in parsed["technical_skills"].items():
        if not value:
            continue
        await _add_memory_row(
            session,
            entity_type="skill_bucket",
            entity_key=bucket,
            doc_id=doc.id,
            user_text=value,
            user_payload_json=None,
            job_context=job_context,
            source_text_hash=None,
        )
        stats["skills_inserted"] += 1

    # summary
    if parsed["summary"]:
        await _add_memory_row(
            session,
            entity_type="summary",
            entity_key="__scalar__",
            doc_id=doc.id,
            user_text=parsed["summary"],
            user_payload_json=None,
            job_context=job_context,
            source_text_hash=None,
        )
        stats["summary_inserted"] = True

    # tagline
    if parsed["tagline"]:
        await _add_memory_row(
            session,
            entity_type="tagline",
            entity_key="__scalar__",
            doc_id=doc.id,
            user_text=parsed["tagline"],
            user_payload_json=None,
            job_context=job_context,
            source_text_hash=None,
        )
        stats["tagline_inserted"] = True

    return stats


async def _add_memory_row(
    session,
    *,
    entity_type: str,
    entity_key: str,
    doc_id: uuid.UUID,
    user_text: str | None,
    user_payload_json: Any,
    job_context: dict,
    source_text_hash: str | None,
) -> None:
    row = ContentMemory(
        entity_type=entity_type,
        entity_key=entity_key,
        source_doc_id=doc_id,
        source_job_id=None,
        user_text=user_text,
        user_payload_json=user_payload_json,
        job_context=job_context,
        source_text_hash=source_text_hash,
        is_active=True,
    )
    session.add(row)
    await session.flush()


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


async def main():
    docx_paths = sorted(p for p in RESUME_DIR.glob("*.docx") if not p.name.startswith("~$"))
    if not docx_paths:
        logger.warning("No .docx files found in %s", RESUME_DIR)
        return

    logger.info("Found %d resume(s) to ingest from %s", len(docx_paths), RESUME_DIR)

    async with async_session() as session:
        result = await session.execute(select(UserProfile).limit(1))
        profile = result.scalar_one_or_none()
        if profile is None:
            logger.error("No UserProfile in DB — run profile sync first.")
            return
        profile_data = profile.data

        # Keep base templates out of the ingest set.
        skipped: list[str] = []
        kept: list[Path] = []
        for p in docx_paths:
            n = p.name.lower()
            if "base_resume" in n or n.startswith("prateek_puri_cv_rand"):
                skipped.append(p.name)
                continue
            kept.append(p)

        logger.info("Skipping %d non-tailored file(s): %s", len(skipped), skipped)

        all_stats: list[dict] = []
        for path in kept:
            try:
                stats = await ingest_one(session, docx_path=path, profile_data=profile_data)
                if stats is None:
                    continue
                all_stats.append(stats)
                logger.info(
                    "INGESTED %s — research=%d (unmatched=%d) bullets=%d skills=%d summary=%s tagline=%s",
                    path.name,
                    stats["research_inserted"],
                    len(stats["research_unmatched"]),
                    stats["bullet_sets_inserted"],
                    stats["skills_inserted"],
                    stats["summary_inserted"],
                    stats["tagline_inserted"],
                )
                if stats["research_unmatched"]:
                    logger.info("  unmatched titles: %s", stats["research_unmatched"])
            except Exception:
                logger.exception("Failed to ingest %s", path.name)

        await session.commit()

    # Final summary
    total_research = sum(s["research_inserted"] for s in all_stats)
    total_bullets = sum(s["bullet_sets_inserted"] for s in all_stats)
    total_skills = sum(s["skills_inserted"] for s in all_stats)
    print()
    print("=" * 70)
    print(f"Ingested {len(all_stats)} resume(s)")
    print(f"  research_description rows : {total_research}")
    print(f"  experience_bullets_set rows: {total_bullets}")
    print(f"  skill_bucket rows         : {total_skills}")
    print(f"  summary rows              : {sum(1 for s in all_stats if s['summary_inserted'])}")
    print(f"  tagline rows              : {sum(1 for s in all_stats if s['tagline_inserted'])}")
    print("=" * 70)


if __name__ == "__main__":
    asyncio.run(main())
