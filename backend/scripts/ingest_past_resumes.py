"""One-off seeding script: ingest hand-edited past resumes into content_memory.

Walks the .docx files in ``resume/``, parses the structured sections (the docx
was generated by this app's docx_builder so the layout is predictable),
matches research-entry titles back to accomplishment IDs in
``docs/profile_complete.yaml``, and writes:

  1. A synthetic ``Document`` row per resume (job_id=NULL, source preserved
     in ``content_docx_path``).
  2. ``content_memory`` rows: one ``research_description`` per matched
     accomplishment, one ``experience_bullets_set`` per employer, one
     ``skill_bucket`` per non-empty bucket, plus ``summary`` / ``tagline``.

Designed to run once via:
    docker compose exec api python scripts/ingest_past_resumes.py

Idempotent on the unique key (entity_type, entity_key, source_doc_id) — but
re-running creates new ``Document`` rows each time, so prefer to run once.
"""

