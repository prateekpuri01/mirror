# Inside the api container the repo's `resume/` is mounted at /app/resume.
# When run from the host (backend/ as ROOT), it lives at ROOT.parent/resume.
_resume_candidates = [Path("/app/resume"), ROOT.parent / "resume"]
RESUME_DIR = next((p for p in _resume_candidates if p.is_dir()), _resume_candidates[0])

# Section headers (uppercased) emitted by docx_builder._add_section_header.
_HEADER_SUMMARY = "SUMMARY"
_HEADER_RESEARCH = "SELECTED RESEARCH"
_HEADER_EXPERIENCE = "PROFESSIONAL EXPERIENCE"
_HEADER_PUBLICATIONS = "SELECTED PUBLICATIONS"
_HEADER_SKILLS = "TECHNICAL SKILLS"
_HEADER_EDUCATION = "EDUCATION"
_HEADER_AWARDS = "AWARDS & HONORS"

_ALL_HEADERS = {
    _HEADER_SUMMARY,
    _HEADER_RESEARCH,
    _HEADER_EXPERIENCE,
    _HEADER_PUBLICATIONS,
    _HEADER_SKILLS,
    _HEADER_EDUCATION,
    _HEADER_AWARDS,
}

_BULLET_PREFIX = "•"  # • that docx_builder emits as the bullet glyph


# ---------------------------------------------------------------------------
# Filename → (company, title) parser
# ---------------------------------------------------------------------------

# Filename pattern is "{Name} {Company} {Title}.docx" or
# "{Last}_{First}_{Company}_{Title}.docx". The owner name and any
# multi-word companies are derived from profile_data at runtime, so this
# script works for any user — not just whoever wrote it.

_FILENAME_PATTERN_TEMPLATES = (
    # "{Name} {Company} {Title}.docx"
    r"^{name} (?P<company>.+?) (?P<title>.+?)\.docx$",
    # "{Name} {Company}, {Title}.docx" — comma after company
    r"^{name} (?P<company>[^,]+?), (?P<title>.+?)\.docx$",
    # "{Last}_{First}_{Company}_{Title}.docx"
    r"^{last}_{first}_(?P<company>[^_]+)_(?P<title>.+?)\.docx$",
    # "{Name with underscores}_Resume_{Title}.docx" — fallback for older formats
    r"^{name_underscored}_Resume_(?P<title>.+?)(?:\s\(\d+\))?\.docx$",
)


def _build_filename_patterns(name: str) -> list:
    """Compile filename regexes parameterized on the user's name."""
    parts = name.strip().split()
    if not parts:
        return []
    first = parts[0]
    last = parts[-1] if len(parts) > 1 else ""
    name_underscored = "_".join(parts)
    name_escaped = re.escape(name)

    patterns: list = []
    for tmpl in _FILENAME_PATTERN_TEMPLATES:
        try:
            rendered = tmpl.format(
                name=name_escaped,
                first=re.escape(first),
                last=re.escape(last),
                name_underscored=re.escape(name_underscored),
            )
            patterns.append(re.compile(rendered))
        except (re.error, IndexError):
            continue
    return patterns


def parse_filename(
    filename: str,
    *,
    owner_name: str,
    multiword_companies: tuple[str, ...] = (),
) -> tuple[str, str]:
    """Extract (company, title) from a tailored-resume filename.

    ``owner_name`` is the resume owner's full name (taken from profile_data).
    ``multiword_companies`` is an optional list of known multi-word company
    names that the simple regex would otherwise truncate to the first word.
    """
    # Try multi-word companies first so "Lila Sciences..." doesn't truncate to "Lila"
    for company in multiword_companies:
        prefix = f"{owner_name} {company} "
        if filename.startswith(prefix):
            title = filename[len(prefix) :].removesuffix(".docx").strip().replace("_", " ")
            return company, _clean_title_artifact(title)

    for pat in _build_filename_patterns(owner_name):
        m = pat.match(filename)
        if m:
            company = (m.groupdict().get("company") or "").strip().rstrip(",.")
            raw_title = (m.groupdict().get("title") or "").strip().replace("_", " ")
            return company, _clean_title_artifact(raw_title)

    stem = filename.removesuffix(".docx")
    return "", stem


def _clean_title_artifact(title: str) -> str:
    title = re.sub(r"\s+\(\d+\)$", "", title)
    return title.lstrip("- ").strip()


# ---------------------------------------------------------------------------
# .docx parser — relies on the layout produced by app.ai.docx_builder
# ---------------------------------------------------------------------------


def parse_docx(path: Path) -> dict:
    """Walk paragraph text, segment by section header, return structured dict.

    Tagline is the centered paragraph immediately after the name. Sections
    follow a simple linear layout (no tables, no nested elements).
    """
    doc = DocxDocument(str(path))
    paragraphs: list[str] = [p.text for p in doc.paragraphs]

    out = {
        "tagline": "",
        "summary": "",
        "selected_research": [],
        "experience": {},  # display_name → list[bullet_text]
        "technical_skills": {},
        "awards": "",
    }

    # Find the tagline: first non-empty paragraph after the name (which is
    # all-uppercase, contains spaces, and is short).
    name_idx = None
    for i, txt in enumerate(paragraphs):
        stripped = (txt or "").strip()
        if not stripped:
            continue
        # The name paragraph is "PRATEEK PURI" (or similar uppercase).
        if stripped.isupper() and "PURI" in stripped:
            name_idx = i
            break
    if name_idx is not None:
        for j in range(name_idx + 1, min(name_idx + 6, len(paragraphs))):
            tagline = (paragraphs[j] or "").strip()
            if tagline and " · " in tagline:
                out["tagline"] = tagline
                break
            # Some resumes use other separators; accept any short non-empty
            # line that doesn't look like a header or contact info.
            if (
                tagline
                and tagline.upper() not in _ALL_HEADERS
                and "@" not in tagline
                and "linkedin" not in tagline.lower()
            ):
                out["tagline"] = tagline
                break

    # Walk sections.
    current_header: str | None = None
    cur_research: dict | None = None
    cur_employer: str | None = None
    summary_lines: list[str] = []
    awards_lines: list[str] = []

    def commit_research():
        nonlocal cur_research
        if cur_research and (cur_research.get("title") or cur_research.get("description")):
            out["selected_research"].append(cur_research)
        cur_research = None

    for raw in paragraphs:
        text = (raw or "").strip()
        if not text:
            continue
        upper = text.upper()
        if upper in _ALL_HEADERS:
            # Closing whatever was open
            commit_research()
            current_header = upper
            cur_employer = None
            continue

        if current_header == _HEADER_SUMMARY:
            summary_lines.append(text)
            continue

        if current_header == _HEADER_RESEARCH:
            # Format: "{LABEL} — {Title}" with em-dash separator, then
            # a description paragraph below it.
            if " — " in text and (cur_research is None or cur_research.get("description")):
                # New entry
                commit_research()
                label, _, title = text.partition(" — ")
                cur_research = {
                    "category_label": label.strip(),
                    "title": title.strip(),
                    "description": "",
                }
            elif cur_research is not None and not cur_research.get("description"):
                cur_research["description"] = text
            else:
                # Trailing/extra paragraph — append to current description
                if cur_research is not None:
                    cur_research["description"] = (
                        (cur_research.get("description") or "") + " " + text
                    ).strip()
            continue

        if current_header == _HEADER_EXPERIENCE:
            if text.startswith(_BULLET_PREFIX):
                bullet_text = text.lstrip(_BULLET_PREFIX).strip()
                # docx_builder uses "•  " (bullet + two spaces) — strip that
                if cur_employer is None:
                    # Stray bullet before any employer header — skip
                    continue
                out["experience"].setdefault(cur_employer, []).append(bullet_text)
                continue
            # Employer header line: "Org  —  Location" (two-space em-dash separator)
            if "  —  " in text:
                org, _, _location = text.partition("  —  ")
                cur_employer = org.strip()
                out["experience"].setdefault(cur_employer, [])
                continue
            # Title/dates line: "Title  |  Dates" — ignore
            if "  |  " in text:
                continue
            # Anything else under experience — ignore
            continue

        if current_header == _HEADER_SKILLS:
            # Format: "AI Systems: <value>" / "Data Science: <value>" / "Engineering: <value>"
            for label, key in (
                ("AI Systems:", "ai_systems"),
                ("Data Science:", "data_science"),
                ("Engineering:", "engineering"),
            ):
                if text.startswith(label):
                    value = text[len(label) :].strip()
                    if value:
                        out["technical_skills"][key] = value
                    break
            continue

        if current_header == _HEADER_AWARDS:
            awards_lines.append(text)
            continue

        # Other sections (publications, education) — skip in v1.

    commit_research()
    out["summary"] = " ".join(summary_lines).strip()
    out["awards"] = " ".join(awards_lines).strip()
    return out


# ---------------------------------------------------------------------------
# Accomplishment matching
# ---------------------------------------------------------------------------


_STOPWORDS = {
    "a",
    "an",
    "the",
    "of",
    "and",
    "or",
    "for",
    "to",
    "in",
    "with",
    "on",
    "by",
    "at",
    "from",
    "as",
    "is",
    "are",
    "was",
    "were",
    "be",
    "this",
}


def _tokens(text: str) -> set[str]:
    text = re.sub(r"[^\w\s]", " ", text.lower())
    return {t for t in text.split() if t and t not in _STOPWORDS}


def match_accomplishment_id(title: str, catalog: list[dict]) -> str | None:
    """Pick the best-matching accomplishment_id by token overlap with title.

    Falls back to None if the best match is too weak (overlap < 0.3) — the
    research entry will be skipped rather than misattributed.
    """
    title_tokens = _tokens(title)
    if not title_tokens:
        return None
    best_id: str | None = None
    best_score = 0.0
    for a in catalog:
        a_id = a.get("id")
        a_title = a.get("title") or ""
        impact = a.get("impact_summary") or ""
        candidate_tokens = _tokens(a_title) | _tokens(impact)
        if not candidate_tokens:
            continue
        overlap = len(title_tokens & candidate_tokens) / len(title_tokens)
        # Bonus when the accomplishment title's own tokens are mostly covered
        coverage = (
            len(title_tokens & candidate_tokens) / len(candidate_tokens)
            if candidate_tokens
            else 0.0
        )
        score = overlap * 0.7 + coverage * 0.3
        if score > best_score:
            best_score = score
            best_id = a_id
    return best_id if best_score >= 0.3 else None


